/**
 * Từ điển tiếng Việt / tiếng Nhật (i18n).
 *
 * - `vi` là nguồn sự thật về khoá; `ja` bắt buộc khớp đủ khoá (tsc kiểm tra).
 * - Toàn bộ dict là DỮ LIỆU thuần (không hàm) để có thể truyền từ server sang
 *   client component qua `I18nProvider` (React Server Components không serialise
 *   được hàm).
 * - Chuỗi có biến dùng ngoặc đơn `{name}`, render qua `fmt(t.xxx, { name })`.
 *
 * Ngôn ngữ hiện tại lấy từ cookie `senzu-locale` (xem `lib/i18n-server.ts`);
 * đổi ngôn ngữ bằng `components/locale-switcher.tsx`.
 */

import type { DateLocale } from "@/lib/utils";

export type Locale = "vi" | "ja";

export const LOCALES: Locale[] = ["vi", "ja"];
export const LOCALE_COOKIE = "senzu-locale";
export const DEFAULT_LOCALE: Locale = "vi";

/** Nhận giá trị cookie (bất kỳ) -> locale hợp lệ; mặc định tiếng Việt. */
export function resolveLocale(value?: string | null): Locale {
  return value === "ja" ? "ja" : DEFAULT_LOCALE;
}

/** Bộ nhận diện Intl cho số & ngày (`toLocaleString`, `toLocaleDateString`). */
export function intlLocale(locale: Locale): "vi-VN" | "ja-JP" {
  return locale === "ja" ? "ja-JP" : "vi-VN";
}

/**
 * `dateLocale` của từng ngôn ngữ — khai báo tường minh để `t.dateLocale` giữ
 * kiểu `"vi-VN" | "ja-JP"` thay vì bị suy rộng thành `string`.
 */
const DATE_LOCALE: Record<Locale, DateLocale> = {
  vi: "vi-VN",
  ja: "ja-JP",
};

/** Thay `{biến}` trong chuỗi từ điển. */
export function fmt(
  template: string,
  vars?: Record<string, string | number>
): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match
  );
}

